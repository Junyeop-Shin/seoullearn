-- 회원 테이블. 아이디, 비밀번호 해시, 역할, 가입 전 동의 기록(동의한 문서의 시행일, 동의한 일시)만 저장한다.
-- 실명, 학교, 연락처, 멘티 관련 정보를 담는 열이나 테이블은 만들지 않는다.
CREATE TABLE IF NOT EXISTS app_user (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR(20)  NOT NULL UNIQUE,
    password_hash   VARCHAR(100) NOT NULL,
    role            VARCHAR(10)  NOT NULL,
    consent_version VARCHAR(10),
    consented_at    TIMESTAMP WITH TIME ZONE
);
-- 동의 기록 열이 생기기 전에 만든 DB에도 열을 더한다
ALTER TABLE app_user ADD COLUMN IF NOT EXISTS consent_version VARCHAR(10);
ALTER TABLE app_user ADD COLUMN IF NOT EXISTS consented_at TIMESTAMP WITH TIME ZONE;

-- 답 못 한 질문 모음 (매뉴얼 보완 자료). ai-server가 넣고 관리자만 본다.
-- 가드로 가린 질문 문장, 분류(no·partial), 문의처, 날짜(일 단위)만 저장한다.
-- 누가 물었는지 알 수 있는 열(아이디, 접속 주소, 시각)은 만들지 않는다.
-- ai-server/app/unanswered.py가 이 테이블에 넣는다 (열 이름을 바꾸면 그쪽 INSERT도 고친다).
CREATE TABLE IF NOT EXISTS unanswered_question (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question   VARCHAR(300) NOT NULL,
    answerable VARCHAR(10)  NOT NULL,
    route      VARCHAR(20),
    created_on DATE         NOT NULL
);
