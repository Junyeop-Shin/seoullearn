def drop_marks(text: str) -> str:
    """초안 결과에서 가린 자리표시를 뺀다 (가린 정보는 보고서에 쓰지 않는 내용이다). 줄 구성은 그대로 둔다."""
    return "\n".join(re.sub(r"[ \t]{2,}", " ", _MARK.sub("", line)).strip() for line in text.split("\n"))


