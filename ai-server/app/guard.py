def _looks_like_school(word: str, after: str) -> bool:
    """줄인 학교명 패턴에 걸린 낱말이 실제 학교명으로 보이는지."""
    if _SCHOOL_CONTEXT.match(after):
        return True
    if word.endswith(_SCHOOL_TYPES):
        return True
    if any(word.endswith(e) for e in _COMMON_ENDINGS):
        return False
    if word.endswith("고"):
        prev = word[-2]
        has_ss = (ord(prev) - 0xAC00) % 28 == 20  # 받침 ㅆ: 했고, 됐고, 왔고 …
        if prev in _VERB_BEFORE_GO or has_ss:
            return False
    return True


@dataclass
class GuardResult:
    text: str
    safety: bool = False
    pii: list[str] = field(default_factory=list)


def check(text: str) -> GuardResult:
    res = GuardResult(text=text, safety=bool(_SAFETY.search(text)))
    masked = text
    for label, pat, repl in _PII:
        def sub(m, label=label, repl=repl):
            if label == "학교명" and m.group(0) in _NOT_SCHOOL:
                return m.group(0)
            if label == "학교명" and not m.group(0).endswith("학교") and not _looks_like_school(m.group(0), m.string[m.end():]):
                return m.group(0)
            res.pii.append(label)
            return repl
        masked = pat.sub(sub, masked)

    def name_sub(m):
        w = m.group(1)
        # '듣는 학생', '싫어하던 학생', '수업에 학생이', '과제를 학생이': 이름은 '는', '던'이나 조사(에·를·의·와·과 …)로 끝나지 않는다.
        # '결석한 학생', '배정된 학생'은 줄기(결석, 배정)로 가린다
        if w in _NOT_NAME or w[-1] in "는던에를의와과면데게고가" or (w[-1] in "한된할될" and w[:-1] in _NOT_NAME):
            return m.group(0)
        res.pii.append("이름")
        return "[이름]"

    masked = _NAME.sub(name_sub, masked)
    res.text = masked
    res.pii = sorted(set(res.pii))
    return res
