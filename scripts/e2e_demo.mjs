const sent = []
page.on('request', (r) => { if (r.url().includes('/api/')) sent.push(decodeURIComponent(r.url()) + ' ' + (r.postData() || '')) })
const lastBody = (word) => { const x = sent.filter((t) => t.includes(word)).at(-1); return JSON.parse(x.slice(x.indexOf(' ') + 1)) }   // 그 낱말이 든 마지막 요청의 본문
const shot = (n) => page.screenshot({ path: `${out}/${n}.png`, fullPage: true })
const toast = (text) => page.locator('.toast', { hasText: text }).first().waitFor()
